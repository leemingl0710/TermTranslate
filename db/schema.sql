-- PostgreSQL (Neon) schema, converted from MySQL
-- Run order matters because of foreign keys.
-- For a fresh database. To update the existing Neon DB, run db/migrations/001_*.sql instead.

CREATE TABLE users (
  user_id       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username      VARCHAR(50)  NOT NULL,
  password_hash VARCHAR(255) NOT NULL,
  created_at    TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
-- Case-insensitive unique username ("Alice" and "alice" are the same user),
-- matching the old MySQL utf8mb4_0900_ai_ci behavior.
-- Look users up with: WHERE lower(username) = lower(?)
CREATE UNIQUE INDEX users_username_lower_key ON users (lower(username));

-- Shared term dictionary. New terms found during analysis are added with
--   INSERT ... ON CONFLICT (korean_term) DO NOTHING
CREATE TABLE terms (
  term_id      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  korean_term  VARCHAR(100) NOT NULL UNIQUE,
  english_term VARCHAR(100),
  explanation  TEXT
);

-- Deleting a user deletes their documents (and, through them, the analysis results).
CREATE TABLE documents (
  document_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id     INT NOT NULL REFERENCES users (user_id) ON DELETE CASCADE,
  file_name   VARCHAR(255) NOT NULL,
  file_path   VARCHAR(500),
  uploaded_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_documents_user_id ON documents (user_id);

-- Logs are kept when a user is deleted; user_id becomes NULL.
CREATE TABLE api_logs (
  log_id       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id      INT REFERENCES users (user_id) ON DELETE SET NULL,
  request_type VARCHAR(100),
  status       VARCHAR(30),
  created_at   TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_api_logs_user_id ON api_logs (user_id);

-- One analysis of one document. Each column backs a card on the Analysis Results screen.
CREATE TABLE analysis_results (
  result_id       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  document_id     INT NOT NULL REFERENCES documents (document_id) ON DELETE CASCADE,
  source_text     JSONB,  -- extractor output (page, origin, content, ...), kept so re-analysis skips OCR
  translated_text TEXT,   -- full translation of the extracted text
  explanation     TEXT,   -- "Key Concepts" card: key concepts explained simply
  summary         TEXT,   -- "Lecture Summary" card
  exam_questions  TEXT,   -- "Exam Preparation" card: practice questions
  analyzed_at     TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_analysis_results_document_id ON analysis_results (document_id);

-- "Translation" card: which dictionary terms appeared in which analysis.
CREATE TABLE analysis_terms (
  result_id INT NOT NULL REFERENCES analysis_results (result_id) ON DELETE CASCADE,
  term_id   INT NOT NULL REFERENCES terms (term_id) ON DELETE CASCADE,
  PRIMARY KEY (result_id, term_id)
);
CREATE INDEX idx_analysis_terms_term_id ON analysis_terms (term_id);
