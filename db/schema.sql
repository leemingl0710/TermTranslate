-- PostgreSQL (Neon) schema, converted from MySQL
-- Run order matters because of foreign keys.

CREATE TABLE users (
  user_id       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username      VARCHAR(50)  NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  created_at    TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE terms (
  term_id      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  korean_term  VARCHAR(100) NOT NULL,
  english_term VARCHAR(100),
  explanation  TEXT
);

CREATE TABLE documents (
  document_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id     INT NOT NULL REFERENCES users (user_id),
  file_name   VARCHAR(255) NOT NULL,
  file_path   VARCHAR(500),
  uploaded_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_documents_user_id ON documents (user_id);

CREATE TABLE api_logs (
  log_id       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id      INT REFERENCES users (user_id),
  request_type VARCHAR(100),
  status       VARCHAR(30),
  created_at   TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_api_logs_user_id ON api_logs (user_id);

CREATE TABLE analysis_results (
  result_id       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  document_id     INT NOT NULL REFERENCES documents (document_id),
  translated_text TEXT,
  explanation     TEXT,
  summary         TEXT,
  analyzed_at     TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_analysis_results_document_id ON analysis_results (document_id);
